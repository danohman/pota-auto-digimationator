/// The name of a program by its prefix ("US" is "United States of America"), if pota.app listed it.
pub fn name(prefix: &str) -> Option<&'static str> {
    PROGRAMS.binary_search_by_key(&prefix, |(p, _)| p).ok().map(|i| PROGRAMS[i].1)
}

/// The name of a location by its code ("US-GA" is "Georgia"). Two regions sharing a code
/// are joined with " / ".
pub fn location_name(code: &str) -> Option<String> {
    let first = LOCATIONS.partition_point(|(c, _)| *c < code);
    let names: Vec<&str> = LOCATIONS[first..].iter().take_while(|(c, _)| *c == code).map(|(_, n)| *n).collect();
    (!names.is_empty()).then(|| names.join(" / "))
}

/// One location of a park with its names: "US-GA" becomes "US-GA (Georgia; United States of
/// America)". What is unknown is left out, and a name that repeats the program is not said
/// twice.
pub fn describe_location(code: &str) -> String {
    let place = location_name(code);
    let country = code.split_once('-').and_then(|(p, _)| name(p));
    let mut names: Vec<&str> = [place.as_deref(), country].into_iter().flatten().collect();
    names.dedup();
    if names.is_empty() { code.to_string() } else { format!("{code} ({})", names.join("; ")) }
}

/// A park's `locationDesc`, which lists several locations separated by commas when the
/// park spans them ("US-NC,US-VA"), as the hover text: one location on one line, several
/// each on a line of their own.
pub fn location_tip(location: &str) -> String {
    let parts: Vec<String> = location.split(',').map(str::trim).filter(|l| !l.is_empty()).map(describe_location).collect();
    match parts.len() {
        0 => String::new(),
        1 => format!("Park Location: {}", parts[0]),
        _ => format!("Park Locations:\n{}", parts.join("\n")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted() {
        assert!(PROGRAMS.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(LOCATIONS.windows(2).all(|w| w[0] <= w[1]));
    }

    #[test]
    fn locations() {
        assert_eq!(describe_location("US-GA"), "US-GA (Georgia; United States of America)");
        assert_eq!(describe_location("US-AK"), "US-AK (Alaska; United States of America)");
        assert_eq!(describe_location("VA-VA"), "VA-VA (Vatican City; Vatican)");
        assert_eq!(describe_location("PH-CV"), "PH-CV (Cagayan Valley / Central Visayas; Philippines)");
        assert_eq!(describe_location("US-ZZ"), "US-ZZ (United States of America)");
        assert_eq!(describe_location("XX-1"), "XX-1");
    }

    #[test]
    fn tips() {
        assert_eq!(location_tip("US-GA"), "Park Location: US-GA (Georgia; United States of America)");
        assert_eq!(
            location_tip("US-NC, US-VA"),
            "Park Locations:\nUS-NC (North Carolina; United States of America)\nUS-VA (Virginia; United States of America)"
        );
        assert_eq!(location_tip(""), "");
    }

    #[test]
    fn names() {
        assert_eq!(name("US"), Some("United States of America"));
        assert_eq!(name("XX9"), None);
    }
}
