/// The name of a program by its prefix ("US" is "United States of America"), if pota.app listed it.
pub fn name(prefix: &str) -> Option<&'static str> {
    PROGRAMS.iter().find(|(p, _)| *p == prefix).map(|(_, n)| *n)
}

/// A park's `locationDesc` with the country named: "DE-BY" becomes "DE-BY (Germany)". A
/// list such as "US-NC,US-VA" is named part by part; a part whose program is unknown
/// (or that has no dash) is left as it is.
pub fn describe_location(location: &str) -> String {
    location
        .split(',')
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(|l| match l.split_once('-').and_then(|(p, _)| name(p)) {
            Some(n) => format!("{l} ({n})"),
            None => l.to_string(),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn locations() {
        assert_eq!(describe_location("DE-BY"), "DE-BY (Germany)");
        assert_eq!(describe_location("US-NC, US-VA"), "US-NC (United States of America), US-VA (United States of America)");
        assert_eq!(describe_location("XX-1"), "XX-1");
        assert_eq!(describe_location(""), "");
    }

    #[test]
    fn names() {
        assert_eq!(name("US"), Some("United States of America"));
        assert_eq!(name("XX9"), None);
    }
}
